/**
 * The editor fuzz's pure half (tests/editor-fuzz.test.ts drives the browser): a seeded content tree,
 * seeded edits to it — each one message the Builder editor would post into the frame — and a model of
 * what the SDK holds after each message, so the final page can be rendered FRESH and compared.
 *
 * The model follows the official SDK (node_modules/@builder.io/sdk-svelte/src/components/content/
 * components/enable-editor.svelte), which is the contract a drop-in must keep:
 *  - `builder.contentUpdate` { key, data: content } (key === model): the content is MERGED —
 *    `{ ...old, ...new, data: { ...old.data, ...new.data }, meta: { ...old.meta, ...new.meta,
 *    breakpoints: new.meta?.breakpoints || old.meta?.breakpoints } }`;
 *  - `builder.resetState` { model, state }: the root state is merged with `state`; a content update
 *    never resets the root state (so `data.state` in a later update is not re-applied);
 *  - `builder.configureSdk` { contentId, breakpoints }: for the current content id, merged as
 *    `meta.breakpoints`.
 * A fresh render of `fresh()` (its `data.state` = the merged root state) is what the page should
 * show after the edits.
 */

export const EL = '@builder.io/sdk:Element';
export type Block = Record<string, any>;
export type Content = { id: string; data: Record<string, any>; meta?: Record<string, any> };
export type Message = { type: string; data: any };

/** mulberry32 — small, seedable, good enough to pick edits. */
export function rng(seed: number) {
	let a = seed >>> 0;
	return () => {
		a = (a + 0x6d2b79f5) >>> 0;
		let t = a;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v));
const WORDS = ['alpha', 'bravo', 'charlie', 'delta', 'echo', 'foxtrot', 'golf', 'hotel', 'india', 'juliet', 'kilo', 'lima'];
const STYLES: Record<string, string[]> = {
	marginTop: ['0px', '10px', '24px'],
	paddingLeft: ['0px', '8px', '16px'],
	backgroundColor: ['rgb(255, 0, 0)', 'rgb(0, 128, 0)', 'rgb(0, 0, 255)'],
	color: ['rgb(10, 10, 10)', 'rgb(120, 0, 120)'],
	display: ['block', 'flex', 'none'],
	flexDirection: ['row', 'column'],
	width: ['50%', '100%', '200px'],
	fontSize: ['12px', '20px'],
	textAlign: ['left', 'center']
};
const BREAKPOINTS = ['large', 'medium', 'small'] as const;
const TAGS = ['div', 'section', 'article', 'span'];

/**
 * Edit kinds. Each is one editor message. Weight 0 = not generated by default.
 *
 * Excluded (weight 0) because the OFFICIAL SDK 5.2.0 itself does not show them live (found by this
 * test: the live page differs from a fresh load of the same content):
 *  - 'symbol-content': editing a Symbol block's inline `symbol.content` (same entry). The official
 *    Symbol keeps the content it mounted with (`setContent()` returns early while `contentToUse` is
 *    set and the entry is unchanged), so inline content edits never reach the page.
 *  - 'breakpoints' / 'configure-breakpoints': new `meta.breakpoints` (by contentUpdate or
 *    builder.configureSdk). The official Columns' stacking media queries (`columnsStyles()`) keep
 *    the breakpoints the block mounted with — at 1100px with medium=1150 the live columns stay
 *    `row` where a fresh load stacks them to `column`.
 *  - 'columns-stack': changing a Columns block's `stackColumnsAt`. The official Columns keeps its
 *    old `--flex-dir` / `--flex-dir-tablet` vars live.
 *  - 'button-style-binding': adding/removing a `style.color` binding on a Core:Button (or a state
 *    change it depends on). The official Button keeps its mounted `style` attribute live.
 * Turn them on with EDITOR_FUZZ_KINDS=all (or list them) to see how an SDK does beyond the official.
 */
export const KINDS: Record<string, number> = {
	text: 3,
	add: 3,
	remove: 2,
	move: 2,
	style: 3,
	columns: 2,
	showhide: 2,
	bind: 2,
	state: 2,
	tag: 1,
	swap: 1,
	'symbol-data': 1,
	resend: 1,
	'symbol-content': 0,
	breakpoints: 0,
	'configure-breakpoints': 0,
	'columns-stack': 0,
	'button-style-binding': 0
};

export type Slot = { list: Block[]; key: string; owner: Block | null; depth: number };
export type Found = { block: Block; slot: Slot; index: number; path: string };

/** Every list of blocks the editor can put a block into (Symbol content excluded: it is its own content). */
export function slots(content: Content): Slot[] {
	const out: Slot[] = [];
	const visit = (list: Block[], key: string, owner: Block | null, depth: number) => {
		out.push({ list, key, owner, depth });
		for (const b of list) {
			if (b.component?.name === 'Columns') b.component.options.columns.forEach((c: any, i: number) => visit((c.blocks ??= []), `${b.id}.col${i}`, b, depth + 1));
			else if (b.children) visit(b.children, `${b.id}.children`, b, depth + 1);
		}
	};
	visit(content.data.blocks, 'root', null, 0);
	return out;
}

/** Every block, with its slot and its path from the root: each ancestor's slot, tag and component —
 *  what a block's mount legitimately depends on (a new tag or component is a new element). */
export function blocks(content: Content): Found[] {
	const out: Found[] = [];
	const visit = (list: Block[], key: string, path: string) => {
		list.forEach((block, index) => {
			out.push({ block, slot: undefined as never, index, path: `${path}/${key}` });
			const own = `${path}/${key}/<${block.tagName ?? ''}:${block.component?.name ?? ''}>`;
			if (block.component?.name === 'Columns') block.component.options.columns.forEach((c: any, i: number) => visit(c.blocks ?? [], `${block.id}.col${i}`, own));
			else if (block.children) visit(block.children, `${block.id}.children`, own);
		});
	};
	visit(content.data.blocks, 'root', '');
	const by_list = new Map(slots(content).map((s) => [s.list, s]));
	for (const f of out) {
		for (const s of by_list.values()) if (s.list[f.index] === f.block) f.slot = s;
	}
	return out;
}

const contains = (outer: Block, inner: Block): boolean => {
	if (outer === inner) return true;
	const kids = outer.component?.name === 'Columns' ? outer.component.options.columns.flatMap((c: any) => c.blocks ?? []) : (outer.children ?? []);
	return kids.some((k: Block) => contains(k, inner));
};

export class Fuzz {
	r: () => number;
	n = 0;
	seed: number;
	/** The content the editor holds (what it sends in every contentUpdate). */
	editor: Content;
	/** What the SDK should hold after the messages so far (the model above). */
	model: Content;
	root_state: Record<string, any>;
	kinds: string[];

	constructor(seed: number, kinds?: string[]) {
		this.seed = seed;
		this.r = rng(seed);
		const weights = Object.entries(KINDS).filter(([k, w]) => (kinds ? kinds.includes(k) : w > 0));
		this.kinds = weights.flatMap(([k, w]) => Array(Math.max(1, w)).fill(k));
		this.editor = this.initial();
		this.model = clone(this.editor);
		this.root_state = clone(this.editor.data.state);
	}

	int = (a: number, b: number) => a + Math.floor(this.r() * (b - a + 1));
	pick = <T>(xs: readonly T[]): T => xs[Math.floor(this.r() * xs.length)];
	chance = (p: number) => this.r() < p;
	words = (n = this.int(1, 3)) => Array.from({ length: n }, () => this.pick(WORDS)).join(' ');
	id = (kind: string) => `builder-fz${this.seed}-${kind}-${this.n++}`;

	styles(): Record<string, Record<string, string>> | undefined {
		if (!this.chance(0.5)) return undefined;
		const out: Record<string, Record<string, string>> = {};
		for (let i = this.int(1, 2); i > 0; i--) {
			const bp = this.chance(0.7) ? 'large' : this.pick(BREAKPOINTS);
			const prop = this.pick(Object.keys(STYLES));
			(out[bp] ??= {})[prop] = this.pick(STYLES[prop]);
		}
		return out;
	}

	make(kind: string, depth: number): Block {
		const base = (id: string, rest: Block): Block => {
			const b: Block = { '@type': EL, '@version': 2, id, ...rest };
			const rs = this.styles();
			if (rs) b.responsiveStyles = rs;
			return b;
		};
		const kids = (n: number) => (depth >= 3 ? [] : Array.from({ length: n }, () => this.make(this.pick(['text', 'text', 'button', 'counter', 'box']), depth + 1)));
		switch (kind) {
			case 'text':
				return base(this.id('text'), { component: { name: 'Text', options: { text: `<p>${this.words()}</p>` } } });
			case 'button':
				return base(this.id('button'), { component: { name: 'Core:Button', options: { text: this.words(1) } } });
			case 'counter':
				return base(this.id('counter'), { component: { name: 'Counter', options: { label: this.words(1) } } });
			case 'box': {
				const b = base(this.id('box'), { children: kids(this.int(0, 2)) });
				if (this.chance(0.3)) b.tagName = this.pick(TAGS);
				return b;
			}
			case 'section':
				return base(this.id('section'), { component: { name: 'Core:Section', options: { maxWidth: 1200 } }, children: kids(this.int(1, 2)) });
			case 'columns':
				return base(this.id('columns'), {
					component: {
						name: 'Columns',
						options: { space: this.pick([0, 10, 20, 40]), columns: Array.from({ length: this.int(2, 3) }, () => ({ blocks: kids(this.int(0, 2)) })) }
					}
				});
			case 'symbol': {
				const sym_id = this.id('sym');
				return base(this.id('symbol'), {
					component: {
						name: 'Symbol',
						options: {
							symbol: {
								model: 'symbol',
								entry: sym_id,
								data: { label: this.words(1) },
								content: {
									id: sym_id,
									data: {
										blocks: [
											{ '@type': EL, id: `${sym_id}-label`, component: { name: 'Text', options: { text: '' } }, bindings: { 'component.options.text': 'state.label' } },
											{ '@type': EL, id: `${sym_id}-text`, component: { name: 'Text', options: { text: `<p>${this.words()}</p>` } } }
										]
									}
								}
							}
						}
					}
				});
			}
		}
		throw new Error(kind);
	}

	initial(): Content {
		const must = ['text', 'text', 'counter', 'counter', 'columns', 'symbol', 'box'];
		const extra = Array.from({ length: this.int(0, 3) }, () => this.pick(['text', 'button', 'box', 'section', 'counter']));
		const list = [...must, ...extra].map((k) => this.make(k, 0));
		for (let i = list.length - 1; i > 0; i--) {
			const j = this.int(0, i);
			[list[i], list[j]] = [list[j], list[i]];
		}
		return {
			id: `fuzz-${this.seed}`,
			data: { state: { title: 'Title from state', flag: true, color: 'rgb(200, 0, 0)' }, blocks: list },
			meta: {}
		};
	}

	/** The SDK side: apply one message to the model (the official SDK's semantics, see the top). */
	apply(msg: Message) {
		const merge = (c: Partial<Content>) => {
			const old = this.model;
			this.model = {
				...old,
				...(c as Content),
				data: { ...old.data, ...c.data },
				meta: { ...old.meta, ...c.meta, breakpoints: c.meta?.breakpoints || old.meta?.breakpoints }
			};
		};
		if (msg.type === 'builder.contentUpdate' && msg.data.key === 'page') merge(clone(msg.data.data));
		else if (msg.type === 'builder.resetState' && msg.data.model === 'page') this.root_state = { ...this.root_state, ...clone(msg.data.state) };
		else if (msg.type === 'builder.configureSdk' && msg.data.contentId === this.model.id && msg.data.breakpoints) merge({ meta: { breakpoints: clone(msg.data.breakpoints) } });
	}

	/** The content a fresh page load should be given to show what the edited page shows. */
	fresh(): Content {
		const c = clone(this.model);
		c.data.state = clone(this.root_state);
		if (c.meta && !c.meta.breakpoints) delete c.meta.breakpoints;
		return c;
	}

	update(): Message {
		return { type: 'builder.contentUpdate', data: { key: 'page', data: { id: this.editor.id, data: clone(this.editor.data) } } };
	}

	/** One seeded edit: changes `this.editor` and returns the message; also applied to the model. */
	step(): { kind: string; desc: string; msg: Message } {
		for (let tries = 0; tries < 100; tries++) {
			const kind = this.pick(this.kinds);
			const out = this.edit(kind);
			if (out) {
				this.apply(out.msg);
				return { kind, ...out };
			}
		}
		throw new Error('no applicable edit');
	}

	edit(kind: string): { desc: string; msg: Message } | null {
		const all = blocks(this.editor);
		const of = (pred: (b: Block) => boolean) => all.filter((f) => pred(f.block));
		const name = (b: Block) => b.component?.name;
		const done = (desc: string) => ({ desc, msg: this.update() });
		switch (kind) {
			case 'text': {
				const ts = of((b) => name(b) === 'Text' || name(b) === 'Core:Button');
				if (!ts.length) return null;
				const f = this.pick(ts);
				const words = this.words();
				f.block.component.options.text = name(f.block) === 'Text' ? `<p>${words}</p>` : words;
				return done(`text ${f.block.id} = "${words}"`);
			}
			case 'add': {
				if (all.length > 40) return null;
				const slot = this.pick(slots(this.editor).filter((s) => s.depth < 3));
				const b = this.make(this.pick(['text', 'text', 'button', 'counter', 'box', 'columns', 'section', 'symbol']), slot.depth);
				const at = this.int(0, slot.list.length);
				slot.list.splice(at, 0, b);
				return done(`add ${b.id} into ${slot.key}[${at}]`);
			}
			case 'remove': {
				if (all.length < 4) return null;
				const f = this.pick(all);
				f.slot.list.splice(f.index, 1);
				return done(`remove ${f.block.id} from ${f.slot.key}[${f.index}]`);
			}
			case 'move': {
				const f = this.pick(all);
				const targets = slots(this.editor).filter((s) => !s.owner || !contains(f.block, s.owner));
				f.slot.list.splice(f.index, 1);
				const slot = this.pick(targets);
				const at = this.int(0, slot.list.length);
				slot.list.splice(at, 0, f.block);
				return done(`move ${f.block.id} ${f.slot.key}[${f.index}] -> ${slot.key}[${at}]`);
			}
			case 'style': {
				const f = this.pick(all);
				const bp = this.pick(BREAKPOINTS);
				const prop = this.pick(Object.keys(STYLES));
				const rs = (f.block.responsiveStyles ??= {});
				if (rs[bp]?.[prop] && this.chance(0.4)) {
					delete rs[bp][prop];
					return done(`style ${f.block.id} ${bp}.${prop} removed`);
				}
				const v = this.pick(STYLES[prop]);
				(rs[bp] ??= {})[prop] = v;
				return done(`style ${f.block.id} ${bp}.${prop} = ${v}`);
			}
			case 'columns': {
				const cs = of((b) => name(b) === 'Columns');
				if (!cs.length) return null;
				const cb = this.pick(cs).block;
				const o = cb.component.options;
				const id = cb.id;
				const what = this.pick(['space', 'add-column', 'remove-column', 'widths']);
				if (what === 'space') o.space = this.pick([0, 10, 20, 40]);
				else if (what === 'add-column') o.columns.splice(this.int(0, o.columns.length), 0, { blocks: [this.make('text', 1)] });
				else if (what === 'remove-column') {
					if (o.columns.length < 2) return null;
					o.columns.splice(this.int(0, o.columns.length - 1), 1);
				} else if (what === 'widths') {
					const ws = o.columns.map(() => this.int(1, 4));
					const sum = ws.reduce((a: number, b: number) => a + b, 0);
					o.columns.forEach((c: any, i: number) => (c.width = Math.round((ws[i] / sum) * 100)));
				}
				return done(`columns ${what} (${id})`);
			}
			case 'columns-stack': {
				const cs = of((b) => name(b) === 'Columns');
				if (!cs.length) return null;
				const b = this.pick(cs).block;
				b.component.options.stackColumnsAt = this.pick(['tablet', 'mobile', 'never']);
				return done(`columns-stack ${b.id} = ${b.component.options.stackColumnsAt}`);
			}
			case 'showhide': {
				const f = this.pick(all);
				const b = f.block;
				const what = this.pick(['hide-static', 'bind-show', 'bind-hide', 'clear']);
				if (what === 'hide-static') b.hide = !b.hide;
				else if (what === 'clear') {
					delete b.hide;
					if (b.bindings) (delete b.bindings.show, delete b.bindings.hide);
				} else (b.bindings ??= {})[what === 'bind-show' ? 'show' : 'hide'] = this.pick(['state.flag', '!state.flag']);
				return done(`showhide ${what} ${b.id}`);
			}
			case 'bind':
			case 'button-style-binding': {
				const pool = kind === 'bind' ? of((b) => name(b) !== 'Core:Button') : of((b) => name(b) === 'Core:Button');
				if (!pool.length) return null;
				const b = this.pick(pool).block;
				const bindings = (b.bindings ??= {});
				if (kind === 'bind' && name(b) === 'Text' && this.chance(0.6)) {
					if (bindings['component.options.text']) delete bindings['component.options.text'];
					else bindings['component.options.text'] = 'state.title';
					return done(`bind text ${b.id} ${bindings['component.options.text'] ? 'on' : 'off'}`);
				}
				if (bindings['style.color']) delete bindings['style.color'];
				else bindings['style.color'] = 'state.color';
				return done(`bind style.color ${b.id} ${bindings['style.color'] ? 'on' : 'off'}`);
			}
			case 'state': {
				const what = this.pick(['title', 'flag', 'color']);
				const state =
					what === 'title' ? { title: this.words() } : what === 'flag' ? { flag: !this.root_state.flag } : { color: this.pick(STYLES.backgroundColor) };
				return { desc: `resetState ${JSON.stringify(state)}`, msg: { type: 'builder.resetState', data: { model: 'page', state } } };
			}
			case 'tag': {
				const bs = of((b) => !b.component);
				if (!bs.length) return null;
				const b = this.pick(bs).block;
				b.tagName = this.pick(TAGS);
				return done(`tag ${b.id} = ${b.tagName}`);
			}
			case 'swap': {
				const bs = of((b) => ['Text', 'Core:Button', 'Core:Section'].includes(name(b)) || (!b.component && !!b.children));
				if (!bs.length) return null;
				const b = this.pick(bs).block;
				const from = name(b) ?? 'Box';
				if (from === 'Text') {
					b.component = { name: 'Core:Button', options: { text: b.component.options.text.replace(/<[^>]+>/g, '') } };
					// (a Button's style bindings are 'button-style-binding', off by default: see KINDS)
					if (!this.kinds.includes('button-style-binding')) delete b.bindings?.['style.color'];
				}
				else if (from === 'Core:Button') b.component = { name: 'Text', options: { text: `<p>${b.component.options.text}</p>` } };
				else if (from === 'Core:Section') delete b.component;
				else b.component = { name: 'Core:Section', options: { maxWidth: 1200 } };
				return done(`swap ${b.id} ${from} -> ${name(b) ?? 'Box'}`);
			}
			case 'symbol-data': {
				const ss = of((b) => name(b) === 'Symbol');
				if (!ss.length) return null;
				const b = this.pick(ss).block;
				b.component.options.symbol.data = { ...b.component.options.symbol.data, label: this.words(1) };
				return done(`symbol-data ${b.id} label = ${b.component.options.symbol.data.label}`);
			}
			case 'symbol-content': {
				const ss = of((b) => name(b) === 'Symbol');
				if (!ss.length) return null;
				const b = this.pick(ss).block;
				const inner = b.component.options.symbol.content.data.blocks;
				inner[inner.length - 1].component.options.text = `<p>${this.words()}</p>`;
				return done(`symbol-content ${b.id}`);
			}
			case 'breakpoints':
			case 'configure-breakpoints': {
				const breakpoints = { small: this.pick([500, 600, 640]), medium: this.pick([760, 991, 1150]) };
				if (kind === 'breakpoints') {
					const msg = this.update();
					msg.data.data.meta = { breakpoints };
					return { desc: `meta.breakpoints = ${JSON.stringify(breakpoints)}`, msg };
				}
				return { desc: `configureSdk breakpoints = ${JSON.stringify(breakpoints)}`, msg: { type: 'builder.configureSdk', data: { contentId: this.editor.id, breakpoints } } };
			}
			case 'resend':
				return done('resend the same content');
		}
		return null;
	}
}
